function at(dayOffset: number, hhmm: string, minutesToAdd = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  const [h, m] = hhmm.split(":").map(Number);
  d.setHours(h ?? 0, (m ?? 0) + minutesToAdd, 0, 0);
  return d.toISOString();
}

